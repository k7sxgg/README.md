    private int linhaParaEditar = -1;

    public void atualizarPedidoNaLista(Pedido p) {
        listaPedido.set(linhaParaEditar, p);
        linhaParaEditar = -1;
        atualizarTabela();
    }

    public void adicionarPedido(Pedido p) {
        for (Pedido existente : listaPedido) {
            if (existente.getCodigo() == p.getCodigo()) {
                JOptionPane.showMessageDialog(this, "Erro: Já existe um pedido com este código!");
                return;
            }
        }

        listaPedido.add(p);
        atualizarTabela();
    }

    public void atualizarTabela() {
        javax.swing.table.DefaultTableModel modelo = (javax.swing.table.DefaultTableModel) tblPedidos.getModel();
        modelo.setRowCount(0);

        for (Pedido p : listaPedido) {
            modelo.addRow(new Object[]{
                p.getCodigo(),
                p.getCliente(),
                p.getTamanho(),
                p.getTipoEntrega(),
                p.isBordaRecheada() ? "Sim" : "Não",
                p.isQueijoExtra() ? "Sim" : "Não",
                p.isRefrigerante() ? "Sim" : "Não",
                String.format("R$ %.2f", p.getValorTotal())
            });

        }
    }

