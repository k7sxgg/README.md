    private void jButtonEditActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonEditActionPerformed
        linhaParaEditar = tblPedidos.getSelectedRow();

        if (linhaParaEditar == -1) {
            JOptionPane.showMessageDialog(this, "Selecione um pedido na tabela para editar.");
            return;
        }

        Pedido p = listaPedido.get(linhaParaEditar);

        TelaPedidoPizza telaPedido = new TelaPedidoPizza();
        telaPedido.setTelaPrincipal(this);
        telaPedido.preencherParaEdicao(p);
        telaPedido.setVisible(true);

    }//GEN-LAST:event_jButtonEditActionPerformed

    private void jButtonExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonExcluirActionPerformed
        int linhaSelecionada = tblPedidos.getSelectedRow();

        if (linhaSelecionada == -1) {
            JOptionPane.showMessageDialog(this, "Selecione um pedido na tabela para excluir.");
            return;
        }

        int confirmacao = JOptionPane.showConfirmDialog(
                this,
                "Deseja realmente excluir o pedido selecionado?",
                "Confirmação",
                JOptionPane.YES_NO_OPTION
        );

        if (confirmacao == JOptionPane.YES_OPTION) {
            listaPedido.remove(linhaSelecionada);
            atualizarTabela();
            JOptionPane.showMessageDialog(this, "Pedido excluído com sucesso.");
        }
    }//GEN-LAST:event_jButtonExcluirActionPerformed

