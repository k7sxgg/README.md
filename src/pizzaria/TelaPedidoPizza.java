    public void preencherParaEdicao(Pedido p) {
        isEdicao = true;
        jTextFieldCod.setText(String.valueOf(p.getCodigo()));
        jTextFieldCod.setEditable(false);
        jTextFieldCliente.setText(p.getCliente());

        if (p.getTamanho().equals("Pequena")) {
            jRadioButtonPequena.setSelected(true);
        } else if (p.getTamanho().equals("Média")) {
            jRadioButtonMedia.setSelected(true);
        } else {
            jRadioButtonGrande.setSelected(true);
        }

        if (p.getTipoEntrega().contains("Retirada")) {
            jComboBoxEntrega.setSelectedIndex(1);
        } else if (p.getTipoEntrega().contains("Bairro")) {
            jComboBoxEntrega.setSelectedIndex(2);
        } else {
            jComboBoxEntrega.setSelectedIndex(3);
        }

        jCheckBoxBorda.setSelected(p.isBordaRecheada());
        jCheckBoxQueijo.setSelected(p.isQueijoExtra());
        jCheckBoxRefri.setSelected(p.isRefrigerante());
    }

