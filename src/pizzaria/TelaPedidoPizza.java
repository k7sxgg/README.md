    private void jButtonSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonSalvarActionPerformed
        if (jTextFieldCod.getText().trim().isEmpty() || jTextFieldCliente.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "O código e o nome do cliente são obrigatórios!");
            return;
        }

        if (!jRadioButtonPequena.isSelected() && !jRadioButtonMedia.isSelected() && !jRadioButtonGrande.isSelected()) {
            JOptionPane.showMessageDialog(this, "Selecione o tamanho da pizza!");
            return;
        }

        if (jComboBoxEntrega.getSelectedIndex() == 0) {
            JOptionPane.showMessageDialog(this, "Selecione o tipo de entrega!");
            return;
        }

        try {
            int codigo = Integer.parseInt(jTextFieldCod.getText());
            String cliente = jTextFieldCliente.getText();
            float valorTotal = 0f;

            String tamanho = "";
            if (jRadioButtonPequena.isSelected()) {
                valorTotal += 30.0f;
                tamanho = "Pequena";
            } else if (jRadioButtonMedia.isSelected()) {
                valorTotal += 45.0f;
                tamanho = "Média";
            } else if (jRadioButtonGrande.isSelected()) {
                valorTotal += 65.0f;
                tamanho = "Grande";
            }

            String entrega = jComboBoxEntrega.getSelectedItem().toString();
            if (jComboBoxEntrega.getSelectedIndex() == 2) {
                valorTotal += 5.0f;
            } else if (jComboBoxEntrega.getSelectedIndex() == 3) {
                valorTotal += 15.0f;
            }

            boolean borda = jCheckBoxBorda.isSelected();
            boolean queijo = jCheckBoxQueijo.isSelected();
            boolean refri = jCheckBoxRefri.isSelected();

            if (borda) {
                valorTotal += 8.0f;
            }
            if (queijo) {
                valorTotal += 6.0f;
            }
            if (refri) {
                valorTotal += 7.0f;
            }

            jTextAreaTotal.setText(String.format("Total: R$ %.2f", valorTotal));

            Pedido novoPedido = new Pedido(codigo, cliente, tamanho, entrega, borda, queijo, refri, valorTotal);

            if (telaPrincipal != null) {
                if (isEdicao) {
                    telaPrincipal.atualizarPedidoNaLista(novoPedido);
                    JOptionPane.showMessageDialog(this, "Pedido atualizado com sucesso!");
                } else {
                    telaPrincipal.adicionarPedido(novoPedido);
                    JOptionPane.showMessageDialog(this, "Pedido cadastrado com sucesso!");
                }
                this.dispose();
            }

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "O código deve ser um número inteiro válido!");
        }
    }//GEN-LAST:event_jButtonSalvarActionPerformed

